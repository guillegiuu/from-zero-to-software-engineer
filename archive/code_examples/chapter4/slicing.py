# Slicing de listas en Python

numeros = [0, 1, 2, 3, 4, 5]

print("Lista original:", numeros)

# Desde índice 1 hasta 3 (no incluye el 4)
print("numeros[1:4]:", numeros[1:4])

# Desde el inicio hasta índice 2
print("numeros[:3]:", numeros[:3])

# Desde índice 3 hasta el final
print("numeros[3:]:", numeros[3:])

# Copia de la lista
print("Copia completa:", numeros[:])
