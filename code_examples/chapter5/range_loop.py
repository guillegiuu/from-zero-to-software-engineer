# 🔁 FOR + RANGE

# Ejemplo 1: range básico
for i in range(5):
    print("i:", i)

# 🧠 Resultado:
# 0, 1, 2, 3, 4


# Ejemplo 2: range con inicio y fin
for i in range(1, 6):
    print("Número:", i)

# 🧠 Resultado:
# 1, 2, 3, 4, 5


# Ejemplo 3: range con paso
for i in range(0, 10, 2):
    print("Par:", i)

# 🧠 Resultado:
# 0, 2, 4, 6, 8
