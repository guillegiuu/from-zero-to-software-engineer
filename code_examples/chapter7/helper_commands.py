# Archivo: helper_commands.py

# --------------------------------------------------
# ¿Qué hace este archivo?
# --------------------------------------------------
# Este archivo muestra comandos de ayuda que mejoran
# la productividad en la terminal.
# Incluye ejemplos y comportamiento esperado.

# --------------------------------------------------
# 1) clear
# --------------------------------------------------
# Limpia la pantalla de la terminal

# Ejemplo:
# clear

# Resultado:
# La terminal se limpia (como "reset visual")

# --------------------------------------------------
# 2) history
# --------------------------------------------------
# Muestra el historial de comandos usados

# Ejemplo:
# history

# Output:
# 1  ls
# 2  cd proyectos
# 3  touch app.py

# --------------------------------------------------
# 3) Flechas ↑ ↓
# --------------------------------------------------
# Permiten navegar entre comandos anteriores

# Ejemplo mental:

# ↑  → vuelve al último comando
# ↑  → sigue retrocediendo
# ↓  → avanza

# --------------------------------------------------
# 4) Tab (autocompletado)
# --------------------------------------------------
# Autocompleta nombres de archivos y carpetas

# Ejemplo:

# Escribís:
# cd pro

# Presionás TAB →

# Resultado:
# cd proyectos

# --------------------------------------------------
# EJEMPLO VISUAL (ASCII)
# --------------------------------------------------

# Escribís:
# cd pro[TAB]

# Terminal:
# cd proyectos

# --------------------------------------------------
# IDEA CLAVE
# --------------------------------------------------
# Estos comandos no crean ni navegan,
# pero hacen que trabajar en terminal sea mucho más rápido.
