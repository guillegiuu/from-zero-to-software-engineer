# Archivo: file_and_folder_creation.py

# --------------------------------------------------
# ¿Qué hace este archivo?
# --------------------------------------------------
# Este archivo muestra cómo crear carpetas y archivos
# desde la terminal usando mkdir y touch.
# Incluye ejemplos visuales en ASCII para entender
# el antes y el después.

# --------------------------------------------------
# ANTES (ASCII)
# --------------------------------------------------

# /home/guille
# ├── proyectos
# └── notas.txt

# --------------------------------------------------
# 1) mkdir
# --------------------------------------------------
# mkdir sirve para crear una carpeta nueva.

# Ejemplo:
# mkdir ejercicios

# Resultado esperado:
# se crea una carpeta llamada "ejercicios"

# --------------------------------------------------
# DESPUÉS DE mkdir (ASCII)
# --------------------------------------------------

# /home/guille
# ├── proyectos
# ├── ejercicios
# └── notas.txt

# --------------------------------------------------
# 2) touch
# --------------------------------------------------
# touch sirve para crear un archivo vacío.

# Ejemplo:
# touch app.py

# Resultado esperado:
# se crea un archivo vacío llamado "app.py"

# --------------------------------------------------
# DESPUÉS DE touch (ASCII)
# --------------------------------------------------

# /home/guille
# ├── proyectos
# ├── ejercicios
# ├── app.py
# └── notas.txt

# --------------------------------------------------
# EJEMPLO COMBINADO
# --------------------------------------------------
# mkdir proyectos_nuevos
# cd proyectos_nuevos
# touch main.py

# Resultado:

# /home/guille
# ├── proyectos
# ├── ejercicios
# ├── app.py
# ├── notas.txt
# └── proyectos_nuevos
#     └── main.py

# --------------------------------------------------
# IDEA CLAVE
# --------------------------------------------------
# mkdir -> crea carpetas
# touch -> crea archivos vacíos
